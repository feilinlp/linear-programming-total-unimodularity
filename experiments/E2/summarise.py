"""Summarise an E2 run without rerunning recognition or replacing censored times.

Usage: python3 summarise.py results/main_run
"""
import argparse
from collections import Counter, defaultdict
import csv
import itertools
import json
import os
from pathlib import Path
import statistics


def summarise(directory, analysis_path=None):
    with (directory / 'results.csv').open() as handle:
        rows = list(csv.DictReader(handle))
    metadata = json.loads((directory / 'metadata.json').read_text())
    repeats = metadata['arguments']['repeats']
    expected = set(itertools.product(metadata['selected_ids'],
                   metadata['arguments']['methods'], range(1, repeats + 1)))
    observed = [(r['instance_id'], r['method'], int(r['repetition'])) for r in rows]
    if not rows or len(observed) != len(set(observed)) or set(observed) != expected:
        raise ValueError('Cannot summarise missing, unexpected or duplicate repetitions')
    grouped = defaultdict(list)
    for row in rows:
        grouped[(row['instance_id'], row['method'])].append(row)
    summaries = []
    for (instance, method), group in grouped.items():
        counts = Counter(row['status'] for row in group)
        complete = counts['ok'] == len(group)
        summaries.append(dict(instance_id=instance, family=group[0]['family'],
            group=group[0]['group'], rows=group[0]['rows'], columns=group[0]['columns'],
            nonzeros=group[0]['nonzeros'], expected_tu=group[0]['expected_tu'], method=method,
            repetitions=len(group), completed=counts['ok'], timeouts=counts['timeout'],
            errors=counts['error'] + counts['incorrect'],
            median_wall_seconds=statistics.median(float(row['wall_seconds']) for row in group) if complete else '',
            median_algorithm_seconds=statistics.median(float(row['algorithm_seconds']) for row in group)
                if complete and all(row['algorithm_seconds'] for row in group) else ''))
    with (directory / 'summary.csv').open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(summaries[0]))
        writer.writeheader()
        writer.writerows(summaries)
    counts = Counter(row['status'] for row in rows)
    lines = ['# E2 measured results', '',
        'Generated by `summarise.py` from this run\'s `results.csv`; environment and parameters are in `metadata.json`.', '',
        f"Recorded invocations: **{len(rows)}**. Completed: **{counts['ok']}**. Timeouts: **{counts['timeout']}**. "
        f"Errors/incorrect decisions: **{counts['error'] + counts['incorrect']}**.", '',
        '## Overall completion', '',
        '| Method | Completed invocations | Timeouts | Inputs completed on every repetition |',
        '|---|---:|---:|---:|']
    for method in ['brute', 'gh', 'cmr']:
        attempts = [r for r in rows if r['method'] == method]
        inputs = [r for r in summaries if r['method'] == method]
        lines.append(f"| {method} | {sum(r['status'] == 'ok' for r in attempts)}/{len(attempts)} | "
                     f"{sum(r['status'] == 'timeout' for r in attempts)} | "
                     f"{sum(r['completed'] == r['repetitions'] for r in inputs)}/{len(inputs)} |")
    lines += ['',
        '## Completion by family and method', '',
        '| Family | Expected TU | Method | Completed invocations / attempts | Fully completed inputs / inputs |',
        '|---|---|---|---:|---:|']
    families = sorted({row['family'] for row in rows})
    for family in families:
        for expected in ['True', 'False']:
            for method in ['brute', 'gh', 'cmr']:
                subset = [r for r in rows if (r['family'], r['expected_tu'], r['method']) == (family, expected, method)]
                if not subset:
                    continue
                inputs = [r for r in summaries if (r['family'], r['expected_tu'], r['method']) == (family, expected, method)]
                finished = sum(r['completed'] == r['repetitions'] for r in inputs)
                lines.append(f"| {family} | {expected} | {method} | {sum(r['status'] == 'ok' for r in subset)}/{len(subset)} | {finished}/{len(inputs)} |")
    lines += ['', '## Per-input timing', '',
        'Full timings and completion counts are in `summary.csv`. Medians are shown only when every recorded repetition completed.',
        'Timeouts are censored observations, not one-second successful solves. Do not compare medians over different surviving input sets.', '',
        '## Interpretation and limits', '',
        'All completed decisions can be compared against construction labels in `results.csv`. A timeout establishes no TU decision.',
        'Analyse TU and non-TU inputs separately; early rejection and obstruction placement can change the latter.',
        'Transformed inputs are paired variants, not independent random draws. Block-cycle inputs exercise 1-sum structure, not general 3-sums.',
        'Wall time includes startup and input/output. Python algorithm time excludes those costs; CMR internal logs use a different timing scope.',
        'These measurements compare Python enumeration with compiled CMR on synthetic families and do not establish asymptotic complexity.', '']
    analysis_path = analysis_path or (directory.parent.parent / 'analysis' / 'analysis.md' if directory.name == 'main_run' else None)
    if analysis_path and analysis_path.exists():
        link = Path(os.path.relpath(analysis_path, directory)).as_posix()
        lines += ['## Scaling and structure analysis', '',
                  f'See [analysis.md]({link}) for runtime-versus-size figures, input-property tables and paired comparisons.', '']
    (directory / 'results.md').write_text('\n'.join(lines))
    return len(rows), counts


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    args = parser.parse_args()
    print(summarise(args.directory))
